import numpy as np
import cv2
'''
255인 칸만 표시(■ = 255, · = 0)
줄0:  ■ ■ · · ·
줄1:  ■ ■ · · ■
줄2:  · · · · ■
- 왼쪽 위 ■ 4개가 서로 붙어 있어서 덩어리 하나
- 오른쪽 ■ 2개가 붙어 있어서 덩어리 하나
- 두 덩어리 사이에는 0인 칸이 있어서 떨어져 있음
각 덩어리는 4칸, 2칸임.
num = 3인 이유: connectedComponentsWithStats는 0인 칸(배경)도 0번 덩어리로 셈
0번: 배경(0인 칸 전부)
1번: 왼쪽 위 덩어리(4칸)
2번: 오른쪽 덩어리 (2칸)
num = 3
color_seeker.py의 67번 줄 if num ==1: "배경만 있다 = 그 색 칸이 하나도 없다"는 뜻. 그래서 area = 0임
stats: 덩어리마다 한 줄 씩, 칸 다섯개가 들어있음
[x, y, 폭, 높이, 칸 수]
[[0 0 5 3 9] 
 [0 0 2 2 4]
 [4 1 1 2 2]]
 - x 0: 배경(0인 칸)이 시작하는 가장 왼쪽 칸 번호가 0
 - y: 0 가장 위쪽 줄 번호가 0
 - 폭 5, 높이 3: 0인 칸이 표 전체에 흩어져 있어서, 그걸 다 감싸는 사각형이 표 전체(가로 5칸 x 세로 3줄)
 - 칸 수 0: 0인 칸의 개수. [표 전체] 15칸 - [255인 칸] 6칸 = 9 
함수가 칸마다 "너는 몇 번 덩어리"라고 번호를 붙이고, stats는 그 번호별로 정리한 표예요. 번호가 붙은 결과가 labels예요. 파일에 print(labels)를 추가해서 실행해 보세요. 이렇게 나올 거예요.
mask                      labels (칸마다 덩어리 번호)
255 255   0   0   0       1 1 0 0 0
255 255   0   0 255       1 1 0 0 2
  0   0   0   0 255       0 0 0 0 2
번호를 붙이는 규칙은 이래요.
- 0인 칸은 전부 0번. 이 함수는 원래 그렇게 만들어졌어요. 그래서 배경이 항상 0번이에요.
- 255인 칸은 붙어 있는 것끼리 같은 번호. 왼쪽 위부터 훑으면서 처음 만난 덩어리가 1번, 다음이 2번이에요.
stats의 한 줄 = labels에서 그 번호가 붙은 칸들만 모아서 잰 값
0번 줄: labels에서 0인 칸만 봄
        → 9개, 칸 0~4번·줄 0~2번에 흩어져 있음 → 그걸 감싸는 사각형 = 폭 5, 높이 3
1번 줄: labels에서 1인 칸만 봄
        → 4개, 칸 0~1번·줄 0~1번에 있음 → 폭 2, 높이 2
2번 줄: labels에서 2인 칸만 봄
        → 2개, 칸 4번·줄 1~2번에 있음 → 폭 1, 높이 2
내가 이해한 것
labels: 칸마다 덩어리 번호
1 1 0 0 0 - 배경
1 1 0 0 2
0 0 0 0 2
[[0 0 5 3 9]
 [0 0 2 2 4]
 [4 1 1 2 2]]
│  칸   │ 값  │              어떻게 나왔나              │
├───────┼─────┼─────────────────────────────────────────┤
│ x     │ 0   │ 1이 있는 칸 번호는 0, 1 → 가장 왼쪽은 0 │
├───────┼─────┼─────────────────────────────────────────┤
│ y     │ 0   │ 1이 있는 줄 번호는 0, 1 → 가장 위는 0   │
├───────┼─────┼─────────────────────────────────────────┤
│ 폭    │ 2   │ 칸 0부터 칸 1까지 → 2칸                 │
├───────┼─────┼─────────────────────────────────────────┤
│ 높이  │ 2   │ 줄 0부터 줄 1까지 → 2줄                 │
├───────┼─────┼─────────────────────────────────────────┤
│ 칸 수 │ 4   │ 1의 개수 → 4개
'''
mask = np.array([[255, 255, 0, 0, 255],
                 [255, 255, 0, 0, 255],
                 [0, 0, 0, 0, 255]], np.uint8)
num, labels, stats, centroids = cv2.connectedComponentsWithStats(mask)
print(num) # 3 (배경까지 포함)
print(labels)
'''
      x[0] x[1]  x[2] x[3] x[4]  
y[0][[  1   1     0    0     0] 
y[1] [  1   1     0    0     2]
y[2] [  0   0     0    0     2]]
'''
print(stats)
'''
[[0 0 5 3 9] 0: 배경 덩어리의 맨 왼쪽 x칸, 0 배경 덩어리의 맨 위쪽 y줄, 배경 덩어리 폭(가로): 5, 배경 덩어리 높이(세로): 3, 0의 개수: 9
 [0 0 2 2 4] 0: 덩어리(1)의 맨 왼쪽 x칸, 0 덩어리(1) 맨 위쪽 y줄, 첫 번째 덩어리 폭(가로): 2, 첫 번째 덩어리 높이(세로): 2, 1의 개수: 4
 [4 1 1 2 2]] 4: 덩어리(2)의 칸(x[4])여서 4, 1: 덩어리(2)의 맨 위쪽 y는 y[1]에 위치해서 1,두 번째 덩어리 폭(가로): 1, 두 번째 덩어리 높이(세로): 2, 2의 개수: 2
'''
print(centroids) # 덩어리마다 가운데 [x, y] -> 덩어리 칸들의 x(칸 번호) 평균, y(줄 번호) 평균
'''
1번 덩어리의 x 평균값: (0 + 1 + 0 + 1)/4 = 0.5 | y 평균값: (0 + 0 + 1 + 1) / 4= 0.5
2번 덩어리의 x 평균값: (4 + 4) / 2 = 4 | y 평균값: (1 + 2) / 2 = 1.5
'''

# 1단계
print(stats[1:, cv2.CC_STAT_AREA]) # 덩어리마다 몇 칸인가? stats의 마지막 끝 숫자를 읽으면 됨. 0번째 줄 제외 1번째부터
'''
- stats[1:, ...]: 1번 줄부터 끝까지(0번 배경은 뺌)
- cv2.CC_STAT_AREA: 맨 끝 칸(칸 수)
결과 [4, 2]
'''

# 2단계
print(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
'''
- argmax는 가장 큰 값의 위치(0부터)를 돌려줘요. 값이 아니라 위치예요.
1단계 결과    [4, 2]
위치(argmax)  0  1  <- 4는 0번 위치 -> argmax = 0
'''

# 3단계
biggest = np.argmax(stats[1:, cv2.CC_STAT_AREA]) + 1
print(biggest)
# - 예상: biggest는 몇인가요? 1을 더하는 이유는 1단계에서 무엇을 뺐기 때문일까요? 0번 배경은 뺐기 때문에?
# 덩어리 번호: 1 2 <- 배경(0번)을 빼고 시작했으니 위치 + 1 = 덩어리 번호

# 4단계
print(stats[biggest, cv2.CC_STAT_AREA])
print(centroids[biggest][0])
# - 예상: 가장 큰 덩어리의 칸 수와, 그 덩어리 가운데의 x는 몇인가요? (centroids 결과를 보면 알 수 있어요)
# 가장 큰 덩어리 칸 수는 4, 그 덩어리 가운데 x는 0.5아니였나?